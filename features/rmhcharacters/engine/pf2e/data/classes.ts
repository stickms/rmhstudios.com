/**
 * PF2e Remaster classes: Player Core (bard, cleric, druid, fighter, ranger,
 * rogue, witch, wizard), Player Core 2 (alchemist, barbarian, champion,
 * investigator, monk, oracle, sorcerer, swashbuckler) and Rage of Elements
 * (kineticist).
 *
 * `progression` holds every level-1 proficiency and each later improvement for
 * the class's default path. Where a choice changes the path (a cleric doctrine,
 * a monk's Path to Perfection), the default is noted in the feature text.
 */
import type { LevelFeature, Pf2eClass, Pf2eProgression, Pf2eRank, Pf2eStat } from '../../types';

type Row = [number, Pf2eStat, Pf2eRank];

function prog(...groups: (Row | Row[])[]): Pf2eProgression[] {
  const rows: Row[] = [];
  for (const g of groups) {
    if (typeof g[0] === 'number') rows.push(g as Row);
    else rows.push(...(g as Row[]));
  }
  return rows
    .map(([level, stat, rank]) => ({ level, stat, rank }))
    .sort((a, b) => a.level - b.level);
}

/** Several stats reaching one rank at one level. */
const at = (level: number, stats: Pf2eStat[], rank: Pf2eRank): Row[] =>
  stats.map((s) => [level, s, rank] as Row);

const range = (from: number, to: number, step = 1): number[] => {
  const out: number[] = [];
  for (let i = from; i <= to; i += step) out.push(i);
  return out;
};

const EVEN = range(2, 20, 2);
const ODD_SKILL = range(3, 19, 2);
const ONE_AND_EVEN = [1, ...EVEN];
const EVERY = range(1, 20);
const FROM_2 = range(2, 20);

/**
 * Spell slots for a full caster: `per` slots in each rank once settled, one fewer
 * in a rank the level it arrives; a single 10th-rank slot from 19th level.
 */
function fullSlots(per: number): number[][] {
  const table: number[][] = [];
  for (let level = 1; level <= 20; level++) {
    const row = new Array<number>(10).fill(0);
    const top = Math.min(9, Math.ceil(level / 2));
    for (let rank = 1; rank <= top; rank++) {
      const fresh = rank === top && level % 2 === 1 && level < 19;
      row[rank - 1] = fresh ? per - 1 : per;
    }
    if (level >= 19) row[9] = 1;
    table.push(row);
  }
  return table;
}

