import type { Dnd5eArmor, Dnd5eGear, Dnd5eWeapon } from '../../types';

/** SRD 5.2 weapons, armor and a working set of adventuring gear (2024 rules). */

function W(
  id: string,
  name: string,
  category: Dnd5eWeapon['category'],
  kind: Dnd5eWeapon['kind'],
  damage: string,
  damageType: string,
  properties: string[],
  mastery: string,
  weight: number,
  cost: string,
  extra: { versatile?: string; range?: string } = {},
): Dnd5eWeapon {
  const w: Dnd5eWeapon = { id, name, category, kind, damage, damageType, properties, mastery, weight, cost };
  if (extra.versatile) w.versatile = extra.versatile;
  if (extra.range) w.range = extra.range;
  return w;
}

