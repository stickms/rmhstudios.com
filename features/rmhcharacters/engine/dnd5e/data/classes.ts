import type { Dnd5eClass, LevelFeature } from '../../types';

/**
 * The twelve classes of the System Reference Document 5.2 (2024 rules), each
 * with its SRD subclass. Feature text is a short reminder in plain words.
 * Every class picks its subclass at level 3; level 19 is the Epic Boon.
 */

function F(level: number, name: string, text: string): LevelFeature {
  return { level, name, text };
}

/** A 20-entry table from breakpoints: `{ 1: 'd6', 5: 'd8' }` holds each value until the next key. */
function steps<T extends number | string>(points: Record<number, T>): T[] {
  const out: T[] = [];
  let current = points[1] as T;
  for (let lvl = 1; lvl <= 20; lvl++) {
    const next = points[lvl];
    if (next !== undefined) current = next;
    out.push(current);
  }
  return out;
}

function byLevel<T extends number | string>(fn: (level: number) => T): T[] {
  return Array.from({ length: 20 }, (_, i) => fn(i + 1));
}

