-- Self-test of the spec runner's matchers (runner.lua).

describe('expect', function()
  it('eq compares tables deeply', function()
    expect({ a = 1, b = { 2, 3 } }).eq({ a = 1, b = { 2, 3 } })
    expect(function() expect({ a = 1 }).eq({ a = 2 }) end).error('value.a')
    expect(function() expect({ a = 1, b = 2 }).eq({ a = 1 }) end).error('unexpected key')
  end)

  it('ne, near, truthy, falsy, type', function()
    expect(1).ne(2)
    expect(0.1 + 0.2).near(0.3, 1e-12)
    expect(function() expect(1).near(2, 0.5) end).error('expected')
    expect(0).truthy()
    expect(nil).falsy()
    expect('x').type('string')
  end)

  it('error matches a plain substring', function()
    expect(function() error('boom (x)') end).error('boom (x)')
    expect(function() expect(function() end).error() end).error('none raised')
  end)
end)

describe('hooks', function()
  local log = {}
  before_each(function() log[#log + 1] = 'before' end)
  after_each(function() log[#log + 1] = 'after' end)
  it('runs before_each first', function()
    expect(log[#log]).eq('before')
  end)
  it('ran after_each after the previous test', function()
    expect(log).eq({ 'before', 'after', 'before' })
  end)
end)

describe('environment', function()
  it('sets package.path and RMH_SPEC', function()
    expect(RMH_SPEC.fixtures:find('lib/balatro/mp/__fixtures__/', 1, true) ~= nil).truthy()
    expect(package.path:find('lib/balatro/lua/mp/?.lua', 1, true) ~= nil).truthy()
  end)
  it('starts every file without globals from earlier files', function()
    expect(rawget(_G, 'G')).eq(nil)
  end)
end)
