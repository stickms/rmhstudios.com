/**
 * TEST FIXTURE ONLY — never shipped, never loaded by the game.
 *
 * A hand-written stand-in for the compact weapon JSON the `csgo-ui` channel publishes
 * (scripts/tf2-game/csgo_ui.py → data/<sha>.json, from items_game.txt), in the same shape, for a
 * handful of default weapons. The numbers were written by hand from public knowledge — the CS:GO
 * wiki's weapon pages and the community's published stat tables — and are approximate: they exist so
 * the simulation's tests have realistic inputs, not to reproduce Valve's data. The real game reads
 * the published document at run time (`setCsWeaponData`).
 */

import type { CsItemsDocument } from '../weapon-data';

type Attrs = Record<string, string>;

const T = { terrorists: '1' };
const CT = { 'counter-terrorists': '1' };
const BOTH = { terrorists: '1', 'counter-terrorists': '1' };

function gun(
  defindex: number,
  weaponType: string,
  gearSlot: string,
  usedBy: Record<string, string>,
  sound: string,
  attributes: Attrs,
): CsItemsDocument['items'][string] {
  return {
    defindex,
    prefabs: ['statted_item_base', gearSlot],
    item_gear_slot: gearSlot,
    used_by_classes: usedBy,
    visuals: { weapon_type: weaponType, sound_single_shot: sound },
    attributes,
  };
}

/** Inaccuracy/recoil block helper (stand, crouch, move, jump, land, ladder, fire). */
const acc = (
  stand: number,
  crouch: number,
  move: number,
  jump: number,
  land: number,
  fire: number,
  recStand: number,
  recCrouch: number,
): Attrs => ({
  'inaccuracy stand': String(stand),
  'inaccuracy crouch': String(crouch),
  'inaccuracy move': String(move),
  'inaccuracy jump': String(jump),
  'inaccuracy land': String(land),
  'inaccuracy ladder': String(jump),
  'inaccuracy fire': String(fire),
  'recovery time stand': String(recStand),
  'recovery time crouch': String(recCrouch),
});

