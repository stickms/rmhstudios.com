/**
 * Just enough of a studio model (.mdl, studiohdr_t v44–49) for the game:
 * bounds, eye/illumination positions, flags, surface prop, contents, the
 * material and skin tables. Offsets follow the on-disk (32-bit pointer)
 * layout of studiohdr_t in public/studio.h.
 */

import type { Vec3 } from '../core/vec';
import { BinaryReader, readCString, viewOf } from './binary';

export const MDL_IDENT = 0x54534449; // 'IDST'

/** STUDIOHDR_FLAGS_* (studio.h), the ones gameplay cares about. */
export const STUDIOHDR_FLAGS = {
  AUTOGENERATED_HITBOX: 0x1,
  USES_ENV_CUBEMAP: 0x2,
  FORCE_OPAQUE: 0x4,
  TRANSLUCENT_TWOPASS: 0x8,
  STATIC_PROP: 0x10,
  USES_FB_TEXTURE: 0x20,
  HASSHADOWLOD: 0x40,
  USES_BUMPMAPPING: 0x80,
  USE_SHADOWLOD_MATERIALS: 0x100,
  OBSOLETE: 0x200,
  NO_FORCED_FADE: 0x800,
  CONSTANT_DIRECTIONAL_LIGHT_DOT: 0x2000,
  AMBIENT_BOOST: 0x10000,
} as const;

export interface MdlHeader {
  version: number;
  checksum: number;
  name: string;
  length: number;
  eyePosition: Vec3;
  illumPosition: Vec3;
  hullMin: Vec3;
  hullMax: Vec3;
  viewBBMin: Vec3;
  viewBBMax: Vec3;
  flags: number;
  numBones: number;
  numHitboxSets: number;
  numLocalSequences: number;
  numBodyParts: number;
  numLocalAttachments: number;
  /** Material base names (mstudiotexture_t names), e.g. "barrel01". */
  textures: string[];
  /** Material search directories (cdtextures), e.g. "models\\props_farm\\". */
  textureDirs: string[];
  numSkinRef: number;
  numSkinFamilies: number;
  /** [family][ref] → texture index. */
  skins: number[][];
  surfaceProp: string;
  /** Model keyvalues text ("prop_data", etc.), '' if none. */
  keyValues: string;
  mass: number;
  contents: number;
  numIncludeModels: number;
}

/** SDK: studiohdr_t (read-only subset). Throws on a non-MDL or unsupported version. */
export function parseMdlHeader(bytes: Uint8Array): MdlHeader {
  const view = viewOf(bytes);
  if (bytes.length < 408 || view.getUint32(0, true) !== MDL_IDENT)
    throw new Error('mdl: bad signature');
  const version = view.getInt32(4, true);
  if (version < 44 || version > 49) throw new Error(`mdl: unsupported version ${version}`);
  const r = new BinaryReader(bytes, 8);
  const checksum = r.i32();
  const name = r.fixedString(64);
  const length = r.i32();
  const eyePosition = r.vec3();
  const illumPosition = r.vec3();
  const hullMin = r.vec3();
  const hullMax = r.vec3();
  const viewBBMin = r.vec3();
  const viewBBMax = r.vec3();
  const flags = r.i32();
  const i32 = (o: number) => view.getInt32(o, true);

  const numBones = i32(156);
  const numHitboxSets = i32(172);
  const numLocalSequences = i32(188);
  const numTextures = i32(204);
  const textureIndex = i32(208);
  const numCdTextures = i32(212);
  const cdTextureIndex = i32(216);
  const numSkinRef = i32(220);
  const numSkinFamilies = i32(224);
  const skinIndex = i32(228);
  const numBodyParts = i32(232);
  const numLocalAttachments = i32(240);
  const surfacePropIndex = i32(308);
  const keyValueIndex = i32(312);
  const keyValueSize = i32(316);
  const mass = view.getFloat32(328, true);
  const contents = i32(332);
  const numIncludeModels = i32(336);

  const textures: string[] = [];
  for (let i = 0; i < numTextures && i < 4096; i++) {
    const base = textureIndex + i * 64; // sizeof(mstudiotexture_t) on disk
    if (base + 4 > bytes.length) break;
    textures.push(readCString(bytes, base + i32(base)));
  }
  const textureDirs: string[] = [];
  for (let i = 0; i < numCdTextures && i < 256; i++) {
    const o = cdTextureIndex + i * 4;
    if (o + 4 > bytes.length) break;
    textureDirs.push(readCString(bytes, i32(o)));
  }
  const skins: number[][] = [];
  for (let f = 0; f < numSkinFamilies && f < 1024; f++) {
    const row: number[] = [];
    for (let k = 0; k < numSkinRef; k++) {
      const o = skinIndex + (f * numSkinRef + k) * 2;
      row.push(o + 2 <= bytes.length ? view.getInt16(o, true) : 0);
    }
    skins.push(row);
  }

  return {
    version,
    checksum,
    name,
    length,
    eyePosition,
    illumPosition,
    hullMin,
    hullMax,
    viewBBMin,
    viewBBMax,
    flags,
    numBones,
    numHitboxSets,
    numLocalSequences,
    numBodyParts,
    numLocalAttachments,
    textures,
    textureDirs,
    numSkinRef,
    numSkinFamilies,
    skins,
    surfaceProp:
      surfacePropIndex > 0 && surfacePropIndex < bytes.length
        ? readCString(bytes, surfacePropIndex)
        : '',
    keyValues:
      keyValueIndex > 0 && keyValueSize > 0 && keyValueIndex < bytes.length
        ? readCString(bytes, keyValueIndex, keyValueSize)
        : '',
    mass,
    contents,
    numIncludeModels,
  };
}

/**
 * Candidate material paths for a model's skin (SDK: the studiorender lookup
 * tries each cdtexture directory in order), e.g. "materials/models/props_farm/barrel01.vmt".
 */
export function mdlMaterialPaths(h: MdlHeader, skin = 0): string[][] {
  const family = h.skins[skin] ?? h.skins[0] ?? h.textures.map((_, i) => i);
  return family.map((ti) => {
    const tex = (h.textures[ti] ?? '').replace(/\\/g, '/').toLowerCase();
    return h.textureDirs.map((d) => {
      const dir = d.replace(/\\/g, '/').toLowerCase().replace(/^\/+/, '');
      return `materials/${dir}${dir && !dir.endsWith('/') ? '/' : ''}${tex}.vmt`.replace(
        /\/{2,}/g,
        '/',
      );
    });
  });
}
