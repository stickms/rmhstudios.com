/** Palette contents for a category, hiding anything the city has not unlocked. */
export function unlockedIn(
  category: BuildingCategory,
  peakPopulation: number,
): BuildingDefinition[] {
  return defs.filter(
    (d) => d.category === category && !d.unique && d.unlockPopulation <= peakPopulation,
  );
}

/** The next thing that unlocks, for the "coming up" hint in the palette. */
export function nextUnlock(peakPopulation: number): BuildingDefinition | undefined {
  return defs
    .filter((d) => !d.unique && d.unlockPopulation > peakPopulation)
    .sort((a, b) => a.unlockPopulation - b.unlockPopulation)[0];
}
