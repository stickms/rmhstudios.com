export const BUILDINGS: readonly BuildingDefinition[] = defs;

const BY_ID = new Map(defs.map((d) => [d.id, d]));

export function getDefinition(id: string): BuildingDefinition {
  const def = BY_ID.get(id);
  if (!def) throw new Error(`Isleworks: unknown building definition "${id}"`);
  return def;
}

export function tryGetDefinition(id: string): BuildingDefinition | undefined {
  return BY_ID.get(id);
}

