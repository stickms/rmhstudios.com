/**
 * Isleworks — the building catalogue.
 *
 * Static data, one entry per thing you can place. This is the single source of
 * truth the palette, the simulation, the save format and the 3D models all read
 * from; nothing else in the game hard-codes a building's numbers.
 *
 * Two rules were followed while tuning, and both are load-bearing:
 *
 *  1. **Every category has a distinct failure mode.** Residential fails on land
 *     value, commercial on customers, industrial on pollution it inflicts on
 *     everyone else, utilities on capacity, civic on radius. A player who spams
 *     one category stalls for a reason they can see.
 *  2. **Cost is roughly 10–14 months of the thing's own contribution.** So a
 *     building always pays back, but only if the surrounding city keeps it
 *     working — which is where the interesting decisions live.
 *
 * `unlockPopulation` gates the palette. It reads `peakPopulation`, so a bad
 * month never takes a building away again.
 */

