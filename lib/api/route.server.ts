/**
 * One registered API endpoint (third-pass audit AR3).
 *
 * An endpoint whose handlers go through the wrapper (`implement()` for a typed contract,
 * `defineHandler()` where there is no contract yet) is not a file under `app/routes/api`
 * any more. It is a module in its domain's `api/` folder that exports its handlers by
 * method:
 *
 * ```ts
 * // lib/admin/api/admin.flags.server.ts
 * export const route = apiRoute('/api/admin/flags', {
 *   GET: implement(listAdminFlagsApi, { auth: 'admin' }, async () => …),
 *   PUT: implement(upsertAdminFlagApi, { auth: 'admin', rateLimit: 'write', body }, …),
 * });
 * ```
 *
 * `lib/api/route-table.server.ts` lists every such module (generated by `pnpm api:routes`,
 * checked by `lib/api/__tests__/route-table.test.ts`), and the one splat route
 * `app/routes/api/$.ts` dispatches to it. A handler module is always `*.server.ts`, so
 * the Vite stub plugin keeps it out of the browser bundle whatever imports it.
 *
 * What stays a route file: a handler written without the wrapper, a splat, a stream or
 * SSE response, `/api/auth/$`, `/api/v1/**`. A wrapped handler that reads a multipart
 * body or answers with a file or a redirect is registered like any other: the dispatcher
 * hands it the same `Request` and returns its `Response` untouched.
 */

export type ApiMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'OPTIONS' | 'HEAD';

/** What `defineHandler` / `implement` return, and what the router used to call. */
export type ApiRouteHandler = (args: {
  request: Request;
  params: Record<string, string>;
}) => Promise<Response> | Response;

export type ApiRouteHandlers = Partial<Record<ApiMethod, ApiRouteHandler>>;

export interface ApiRoute<P extends string = string> {
  /** TanStack-style template, the same string as the contract's `path`. */
  readonly path: P;
  readonly handlers: Readonly<ApiRouteHandlers>;
}

const METHODS: ReadonlySet<string> = new Set([
  'GET',
  'POST',
  'PUT',
  'PATCH',
  'DELETE',
  'OPTIONS',
  'HEAD',
]);

export function apiRoute<const P extends string>(path: P, handlers: ApiRouteHandlers): ApiRoute<P> {
  if (!path.startsWith('/api/')) throw new Error(`API route path must start with /api/: ${path}`);
  const methods = Object.keys(handlers);
  if (methods.length === 0) throw new Error(`API route ${path} has no handlers`);
  for (const method of methods) {
    if (!METHODS.has(method)) throw new Error(`API route ${path}: unknown method ${method}`);
  }
  return Object.freeze({ path, handlers: Object.freeze({ ...handlers }) });
}

/**
 * The handler the router would have picked for `method` on a route file with these
 * handlers: an explicit HEAD handler, else GET, for HEAD (RFC 9110 §9.3.2); the exact
 * method otherwise. `undefined` means the route does not answer that method.
 */
export function handlerFor(route: ApiRoute, method: string): ApiRouteHandler | undefined {
  const upper = method.toUpperCase() as ApiMethod;
  if (upper === 'HEAD') return route.handlers.HEAD ?? route.handlers.GET;
  return Object.hasOwn(route.handlers, upper) ? route.handlers[upper] : undefined;
}
