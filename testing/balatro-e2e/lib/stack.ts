/**
 * The match stack for multi-browser Balatro e2e (PLAN §4 WS14, §6.3), modelled on
 * the TF2 P2P smoke (scripts/tf2-game/p2p-smoke.ts): the socket hub and `vite dev`
 * run locally against a throwaway Postgres; accounts are real (multiplayer needs
 * sign-in) and are made through the sign-up API.
 *
 * Two ways to get a stack:
 * - spawn (CI): DATABASE_URL points at a migrated throwaway database and
 *   BETTER_AUTH_SECRET is set; startStack() starts
 *     SOCKET_PORT=<hub> SOCKET_CORS_ORIGIN=<base> tsx server/socket-server/index.ts
 *     VITE_SOCKET_URL=<hub url> VITE_BALATRO_MP_TEST=1 BETTER_AUTH_URL=<base> vite dev --port <web>
 *   and waits for both (hub: an engine.io polling handshake; web: GET /api/ready).
 * - attach (local, stack already up): BALATRO_E2E_BASE_URL (+ BALATRO_E2E_SOCKET_URL,
 *   default http://localhost:7001).
 * Neither → 'unavailable' with the reason; the match project skips, unless
 * BALATRO_E2E_REQUIRE_MATCH=1 (CI), which turns that into a failure.
 *
 * Local requirements (this is what CI provides): Postgres 16 (pgvector image, as in
 * web-ci.yml's integration job), `pnpm exec prisma migrate deploy` on it, Chromium.
 */
import { spawn, type ChildProcess } from 'node:child_process';
import { createWriteStream, mkdirSync, realpathSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { REPO_ROOT } from './static-server';

export type StackConfig =
  | { mode: 'attach'; baseUrl: string; socketUrl: string }
  | {
      mode: 'spawn';
      baseUrl: string;
      socketUrl: string;
      webPort: number;
      hubPort: number;
      databaseUrl: string;
      authSecret: string;
      logDir: string;
    }
  | { mode: 'unavailable'; reason: string };

type Env = Record<string, string | undefined>;

const port = (v: string | undefined, d: number) => {
  const n = Number(v);
  return Number.isInteger(n) && n > 0 && n < 65_536 ? n : d;
};

/** Which stack this environment can provide (pure). */
export function stackConfig(env: Env = process.env): StackConfig {
  if (env.BALATRO_E2E_BASE_URL) {
    return {
      mode: 'attach',
      baseUrl: env.BALATRO_E2E_BASE_URL.replace(/\/$/, ''),
      socketUrl: (env.BALATRO_E2E_SOCKET_URL ?? 'http://localhost:7001').replace(/\/$/, ''),
    };
  }
  if (!env.DATABASE_URL)
    return {
      mode: 'unavailable',
      reason: 'no DATABASE_URL (throwaway Postgres) and no BALATRO_E2E_BASE_URL',
    };
  if (!env.BETTER_AUTH_SECRET || env.BETTER_AUTH_SECRET.length < 32) {
    return {
      mode: 'unavailable',
      reason: 'BETTER_AUTH_SECRET (32+ chars) is required to spawn the app',
    };
  }
  const webPort = port(env.BALATRO_E2E_WEB_PORT, 7997);
  const hubPort = port(env.BALATRO_E2E_HUB_PORT, 7001);
  return {
    mode: 'spawn',
    baseUrl: `http://localhost:${webPort}`,
    socketUrl: `http://localhost:${hubPort}`,
    webPort,
    hubPort,
    databaseUrl: env.DATABASE_URL,
    authSecret: env.BETTER_AUTH_SECRET,
    logDir: env.BALATRO_E2E_LOG_DIR ?? path.join(tmpdir(), 'balatro-e2e-logs'),
  };
}

export interface ProcessSpec {
  name: string;
  command: string;
  args: string[];
  env: Record<string, string>;
}

/**
 * Writes `<dir>/vite.e2e.config.mts`: the repo's vite.config.ts with HMR and the watcher
 * off (an edit — or Tailwind rescanning a new test file — would otherwise hot-update
 * /balatro and stop the engine mid-match), and `server.fs.allow` widened to the real
 * path of node_modules (a git worktree's node_modules may be a link to another checkout).
 * Returns its path.
 */
export function viteWrapperConfig(dir: string): string {
  mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'vite.e2e.config.mts');
  // The real store (a worktree may link node_modules/.pnpm to another checkout's).
  const modules = path.dirname(realpathSync(path.join(REPO_ROOT, 'node_modules/.pnpm')));
  const vite = pathToFileURL(path.join(REPO_ROOT, 'node_modules/vite/dist/node/index.js')).href;
  const base = pathToFileURL(path.join(REPO_ROOT, 'vite.config.ts')).href;
  writeFileSync(
    file,
    [
      '// Generated by testing/balatro-e2e/lib/stack.ts (viteWrapperConfig).',
      `import { mergeConfig } from ${JSON.stringify(vite)};`,
      `import base from ${JSON.stringify(base)};`,
      'export default mergeConfig(base, {',
      `  root: ${JSON.stringify(REPO_ROOT)},`,
      `  server: { hmr: false, watch: null, fs: { allow: ${JSON.stringify([REPO_ROOT, modules])} } },`,
      '});',
      '',
    ].join('\n'),
  );
  return file;
}

/** The two processes of a spawned stack (pure apart from the wrapper config file). */
export function stackProcesses(cfg: Extract<StackConfig, { mode: 'spawn' }>): ProcessSpec[] {
  const common = { DATABASE_URL: cfg.databaseUrl, NODE_ENV: 'development' };
  return [
    {
      name: 'hub',
      command: path.join(REPO_ROOT, 'node_modules/.bin/tsx'),
      args: ['server/socket-server/index.ts'],
      env: {
        ...common,
        SOCKET_PORT: String(cfg.hubPort),
        SOCKET_CORS_ORIGIN: cfg.baseUrl,
        // Software-rendered pages can stall past socket.io's 45 s ping window (TF2 smoke note).
        SOCKET_PING_TIMEOUT: '120000',
        LOG_LEVEL: 'info',
      },
    },
    {
      name: 'web',
      command: path.join(REPO_ROOT, 'node_modules/.bin/vite'),
      // The repo's vite.config.ts through a wrapper (viteWrapperConfig) that turns HMR
      // and the file watcher off: a test page must never reload because a file changed.
      args: [
        'dev',
        '--port',
        String(cfg.webPort),
        '--strictPort',
        '--config',
        viteWrapperConfig(cfg.logDir),
      ],
      env: {
        ...common,
        BETTER_AUTH_SECRET: cfg.authSecret,
        BETTER_AUTH_URL: cfg.baseUrl,
        VITE_SOCKET_URL: cfg.socketUrl,
        VITE_BALATRO_MP_TEST: '1',
      },
    },
  ];
}

/** Polls until fn resolves truthy, or throws after timeoutMs. */
export async function waitFor(
  what: string,
  fn: () => Promise<boolean>,
  timeoutMs: number,
  everyMs = 1000,
): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  let last = '';
  while (Date.now() < deadline) {
    try {
      if (await fn()) return;
    } catch (e) {
      last = e instanceof Error ? e.message : String(e);
    }
    await new Promise((r) => setTimeout(r, everyMs));
  }
  throw new Error(`timed out waiting for ${what}${last ? ` (last error: ${last})` : ''}`);
}

export const hubReady = async (socketUrl: string) =>
  (
    await fetch(`${socketUrl}/socket/?EIO=4&transport=polling`, {
      signal: AbortSignal.timeout(5000),
    })
  ).ok;
export const webReady = async (baseUrl: string) =>
  (await fetch(`${baseUrl}/api/ready`, { signal: AbortSignal.timeout(15_000) })).ok;

export interface RunningStack {
  baseUrl: string;
  socketUrl: string;
  close(): Promise<void>;
}

export async function startStack(
  cfg: StackConfig,
  opts: { timeoutMs?: number } = {},
): Promise<RunningStack> {
  if (cfg.mode === 'unavailable') throw new Error(`match stack unavailable: ${cfg.reason}`);
  const timeoutMs = opts.timeoutMs ?? 300_000;
  const children: ChildProcess[] = [];
  const close = async () => {
    for (const c of children) if (c.exitCode === null) c.kill('SIGTERM');
    await Promise.all(
      children.map((c) => (c.exitCode === null ? new Promise((r) => c.once('exit', r)) : null)),
    );
  };
  if (cfg.mode === 'spawn') {
    mkdirSync(cfg.logDir, { recursive: true });
    for (const p of stackProcesses(cfg)) {
      const log = createWriteStream(path.join(cfg.logDir, `${p.name}.log`));
      const child = spawn(p.command, p.args, {
        cwd: REPO_ROOT,
        env: { ...process.env, ...p.env },
        stdio: ['ignore', 'pipe', 'pipe'],
      });
      child.stdout?.pipe(log);
      child.stderr?.pipe(log);
      child.once('exit', (code) => {
        if (code) log.write(`\n[${p.name} exited ${code}]\n`);
      });
      children.push(child);
    }
  }
  try {
    const exited = () => children.find((c) => c.exitCode !== null);
    const guard = (fn: () => Promise<boolean>) => async () => {
      const dead = exited();
      if (dead) throw new Error(`a stack process exited with ${dead.exitCode} (see the logs)`);
      return fn();
    };
    await waitFor(
      `the hub at ${cfg.socketUrl}`,
      guard(() => hubReady(cfg.socketUrl)),
      timeoutMs,
    );
    await waitFor(
      `the app at ${cfg.baseUrl}`,
      guard(() => webReady(cfg.baseUrl)),
      timeoutMs,
      2000,
    );
  } catch (e) {
    await close();
    throw e;
  }
  return { baseUrl: cfg.baseUrl, socketUrl: cfg.socketUrl, close };
}
