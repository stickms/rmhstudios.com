/* eslint-disable local/no-adhoc-spinner -- in-button busy icon or inline status: <Spinner> renders role="status" and would join the control accessible name */
import { useEffect, useId, useRef, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { ImagePlus, Loader2, Sparkles, Star, Wand2, X } from 'lucide-react';
import { toast } from '@/lib/toast';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import {
  LISTING_PHOTO_ALT_MAX,
  appendPhotos,
  movePhoto,
  normalizeAlts,
  removePhoto,
  setPhotoAlt,
  undescribedCount,
} from '@/lib/homes/photos';

import { AI_IMAGE_TIMEOUT_MS, api } from '@/lib/contract/client';
import { serverError } from '@/lib/http';
import { uploadImagesApi } from '@/lib/media/upload.contract';
import { generateHomeAiImageApi, getHomeAiImageAvailabilityApi } from '@/lib/homes/homes.contract';
interface ImageUploaderProps {
  value: string[];
  /** Subset of `value` that was AI-generated. */
  aiImages: string[];
  /** What each photo shows, in the order of `value`; `''` = not described. */
  alts: string[];
  /** Positions of photos that are not this member's site photos; each is marked and says to replace it. */
  foreign?: ReadonlySet<number>;
  onChange: (images: string[], aiImages: string[], alts: string[]) => void;
  max?: number;
}

/** Upload endpoint accepts up to 4 files per request. */
const CHUNK = 4;

/**
 * Multi-photo manager for a listing. Photos can be uploaded (posted to the
 * shared /api/rmharks/image endpoint) or generated with AI (xAI, via
 * /api/homes/ai-image) from a text prompt. The first image is the cover;
 * AI-generated photos are tagged so the listing shows a "Generated by AI"
 * disclaimer on them. Each photo has a "Describe this photo" field; its description moves and goes with it
 * (`lib/homes/photos.ts`), and a line under the photos says how many have none.
 */
export function ImageUploader({ value, aiImages, alts, foreign, onChange, max = 8 }: ImageUploaderProps) {
  const { t } = useTranslation('listing-photo-alt');
  const idBase = useId();
  const photoAlts = normalizeAlts(value, alts);
  const missing = undescribedCount(value, photoAlts);
  const [uploading, setUploading] = useState(false);
  const [aiOpen, setAiOpen] = useState(false);
  const [aiAvailable, setAiAvailable] = useState(false);
  const [aiPrompt, setAiPrompt] = useState('');
  const [generating, setGenerating] = useState(false);
  const inputRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    let cancelled = false;
    api(getHomeAiImageAvailabilityApi)
      .then((d) => {
        if (!cancelled) setAiAvailable(Boolean(d.available));
      })
      .catch(() => {});
    return () => {
      cancelled = true;
    };
  }, []);

  const atMax = value.length >= max;

  async function handleFiles(fileList: FileList | null) {
    if (!fileList || fileList.length === 0) return;
    const remaining = max - value.length;
    if (remaining <= 0) {
      toast.error(`You can add up to ${max} photos.`);
      return;
    }
    const files = Array.from(fileList).slice(0, remaining);
    setUploading(true);
    try {
      const collected: string[] = [];
      for (let i = 0; i < files.length; i += CHUNK) {
        const form = new FormData();
        for (const f of files.slice(i, i + CHUNK)) form.append('images', f);
        const data = await api(uploadImagesApi, { body: form }).catch((e: unknown) => {
          throw new Error(serverError(e) || 'Upload failed');
        });
        collected.push(...(data.urls ?? []));
      }
      const next = appendPhotos({ images: value, alts: photoAlts }, collected);
      onChange(next.images.slice(0, max), aiImages, next.alts.slice(0, max));
    } catch (err) {
      toast.error(err instanceof Error ? err.message : 'Upload failed');
    } finally {
      setUploading(false);
      if (inputRef.current) inputRef.current.value = '';
    }
  }

  async function generate() {
    const prompt = aiPrompt.trim();
    if (prompt.length < 3) {
      toast.error('Describe the photo you want to generate.');
      return;
    }
    if (atMax) {
      toast.error(`You can add up to ${max} photos.`);
      return;
    }
    setGenerating(true);
    try {
      const data = await api(generateHomeAiImageApi, {
        body: { prompt },
        timeoutMs: AI_IMAGE_TIMEOUT_MS,
      }).catch((error: unknown) => {
        throw new Error(serverError(error) || 'Could not generate an image.');
      });
      if (!data.url) throw new Error('Could not generate an image.');
      const next = appendPhotos({ images: value, alts: photoAlts }, [data.url]);
      onChange(next.images.slice(0, max), [...aiImages, data.url], next.alts.slice(0, max));
      setAiPrompt('');
      toast.success('Image generated');
    } catch (err) {
      toast.error(err instanceof Error ? err.message : 'Could not generate an image.');
    } finally {
      setGenerating(false);
    }
  }

  function remove(index: number) {
    const next = removePhoto({ images: value, alts: photoAlts }, index);
    // The AI mark is by address: keep it while another copy of the same photo is still there.
    onChange(
      next.images,
      aiImages.filter((u) => next.images.includes(u)),
      next.alts,
    );
  }

  function makeCover(index: number) {
    const next = movePhoto({ images: value, alts: photoAlts }, index, 0);
    onChange(next.images, aiImages, next.alts);
  }

  function describe(index: number, text: string) {
    onChange(value, aiImages, setPhotoAlt({ images: value, alts: photoAlts }, index, text).alts);
  }

  return (
    <div>
      <div className="grid grid-cols-2 gap-x-3 gap-y-4 sm:grid-cols-4">
        {value.map((url, i) => {
          const isAi = aiImages.includes(url);
          const fieldId = `${idBase}-alt-${i}`;
          const positionId = `${idBase}-pos-${i}`;
          const described = photoAlts[i] ?? '';
          const isForeign = foreign?.has(i) ?? false;
          return (
            <div key={`${i}-${url}`} className="min-w-0">
              <div
                className={`group relative aspect-square overflow-hidden rounded-site-sm border bg-site-bg-subtle ${isForeign ? 'border-site-danger' : 'border-site-border'}`}
              >
                <img
                  src={url}
                  // Undescribed: the "Photo n of m" line under the tile names it, so the picture adds nothing.
                  alt={described}
                  className="h-full w-full object-cover"
                />
                {i === 0 && (
                  <span className="absolute left-1 top-1 inline-flex items-center gap-1 rounded-full bg-site-media-scrim-strong px-1.5 py-0.5 text-micro font-medium text-site-media-ink">
                    <Star className="h-3 w-3 fill-current" /> Cover
                  </span>
                )}
                {isAi && (
                  <span className="absolute bottom-1 left-1 inline-flex items-center gap-1 rounded-full bg-site-accent/90 px-1.5 py-0.5 text-micro font-semibold text-site-accent-fg">
                    <Sparkles className="h-3 w-3" /> AI
                  </span>
                )}
                <div className="absolute inset-0 flex items-start justify-end gap-1 p-1 transition-opacity sm:opacity-0 sm:group-hover:opacity-100 sm:group-focus-within:opacity-100">
                  {i !== 0 && (
                    <button
                      type="button"
                      onClick={() => makeCover(i)}
                      aria-label="Make cover photo"
                      className="grid h-7 w-7 place-items-center rounded-full bg-site-media-scrim-strong text-site-media-ink hover:bg-site-media-scrim-hover"
                    >
                      <Star className="h-3.5 w-3.5" />
                    </button>
                  )}
                  <button
                    type="button"
                    onClick={() => remove(i)}
                    aria-label="Remove photo"
                    className="grid h-7 w-7 place-items-center rounded-full bg-site-media-scrim-strong text-site-media-ink hover:bg-site-media-scrim-hover"
                  >
                    <X className="h-3.5 w-3.5" />
                  </button>
                </div>
              </div>
              {isForeign && (
                <p role="alert" className="t-meta mt-1.5 text-site-danger" data-slot="homes-photo-not-site">
                  {t('photo-not-site', {
                    defaultValue: 'This photo is not uploaded to this listing. Replace it before you save.',
                  })}
                </p>
              )}
              <p id={positionId} className="t-meta mt-1.5">
                {t('photo-position', {
                  defaultValue: 'Photo {{index}} of {{total}}',
                  index: i + 1,
                  total: value.length,
                })}
              </p>
              <label htmlFor={fieldId} className="t-label mt-1 block">
                {t('describe-photo', { defaultValue: 'Describe this photo' })}
              </label>
              <Textarea
                id={fieldId}
                dir="auto"
                value={photoAlts[i] ?? ''}
                maxLength={LISTING_PHOTO_ALT_MAX}
                onChange={(e) => describe(i, e.target.value)}
                aria-describedby={positionId}
                placeholder={t('describe-photo-example', {
                  defaultValue: 'e.g. Kitchen with a gas hob and a window over the sink',
                })}
                className="mt-1 min-h-20"
              />
            </div>
          );
        })}

        {!atMax && (
          <button
            type="button"
            onClick={() => inputRef.current?.click()}
            disabled={uploading}
            className="flex aspect-square flex-col items-center justify-center gap-1 rounded-site-sm border border-dashed border-site-border text-site-text-muted transition-colors hover:border-site-accent/50 hover:text-site-text disabled:opacity-50"
          >
            {uploading ? (
              <Loader2 className="h-5 w-5 animate-spin" />
            ) : (
              <>
                <ImagePlus className="h-5 w-5" />
                <span className="text-xs">Upload</span>
              </>
            )}
          </button>
        )}
      </div>

      <input aria-label={t('field-photo-files', { defaultValue: 'Choose photos' })}
        ref={inputRef}
        type="file"
        accept="image/png,image/jpeg,image/webp,image/gif"
        multiple
        className="hidden"
        onChange={(e) => handleFiles(e.target.files)}
      />

      {value.length > 0 && (
        <p className="t-body mt-3 text-site-text-muted" aria-live="polite" data-slot="homes-photo-alt-count">
          {missing === 0
            ? t('all-described', { defaultValue: 'Every photo has a description.' })
            : t('undescribed-count', {
                defaultValue_one: '{{count}} photo has no description.',
                defaultValue: '{{count}} photos have no description.',
                count: missing,
              })}
        </p>
      )}

      <div className="mt-3 flex flex-wrap items-center gap-x-3 gap-y-1">
        <p className="text-xs text-site-text-muted">
          Up to {max} photos. The first is the cover — hover to set cover or remove.
        </p>
        {aiAvailable && (
          <button
            type="button"
            onClick={() => setAiOpen((v) => !v)}
            className="inline-flex items-center gap-1 text-xs font-medium text-site-accent hover:underline"
          >
            <Wand2 className="h-3.5 w-3.5" />
            {aiOpen ? 'Hide AI generator' : 'Generate with AI'}
          </button>
        )}
      </div>

      {aiAvailable && aiOpen && (
        <div className="relative mt-3 py-5">
          <label
            htmlFor="ai-prompt"
            className="mb-2 flex items-center gap-2 text-sm font-medium text-site-text"
          >
            <Sparkles className="h-4 w-4 text-site-accent" /> Generate a photo with AI
          </label>
          <Textarea
            id="ai-prompt"
            value={aiPrompt}
            maxLength={500}
            onChange={(e) => setAiPrompt(e.target.value)}
            placeholder="e.g. bright modern living room with hardwood floors and large windows"
            className="min-h-16"
            disabled={generating || atMax}
          />
          <div className="mt-2 flex items-center gap-2">
            <Button
              type="button"
              size="sm"
              onClick={generate}
              loading={generating}
              disabled={atMax}
            >
              {!generating && <Sparkles className="h-4 w-4" />}
              Generate
            </Button>
            <span className="text-xs text-site-text-muted">
              AI photos are labeled “Generated by AI” on your listing.
            </span>
          </div>
        </div>
      )}
    </div>
  );
}
