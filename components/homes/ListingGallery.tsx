/**
 * The photos of a listing: the main photo, its description (when the lister wrote one), and the strip of
 * thumbnails. Every photo is content, so every one has a text alternative (WCAG 1.1.1, s11 14): the lister's
 * description, else "Photo n of m: <title>" with the title isolated so it keeps its own direction.
 */
import { Sparkles } from 'lucide-react';
import { useTranslation } from 'react-i18next';
import type { Listing } from '@/lib/homes/types';
import { isolateText, photoAlt } from '@/lib/homes/photos';

interface ListingGalleryProps {
  listing: Pick<Listing, 'images' | 'aiImages' | 'imageAlts' | 'title'>;
  activeImage: number;
  onSelect: (index: number) => void;
}

/** The text alternative of photo `index`, translated. */
export function usePhotoAlt(listing: Pick<Listing, 'images' | 'imageAlts' | 'title'>): (index: number) => string {
  const { t } = useTranslation('listing-photo-alt');
  return (index) => {
    const alt = photoAlt(listing, index);
    if (alt.kind === 'described') return alt.text;
    return t('photo-fallback', {
      defaultValue: 'Photo {{index}} of {{total}}: {{title}}',
      index: alt.index,
      total: alt.total,
      title: isolateText(alt.title),
    });
  };
}

export function ListingGallery({ listing, activeImage, onSelect }: ListingGalleryProps) {
  const { t } = useTranslation('listing-photo-alt');
  const altFor = usePhotoAlt(listing);
  const images = listing.images;
  if (images.length === 0) return null;
  const current = Math.min(Math.max(activeImage, 0), images.length - 1);
  const main = images[current] as string;
  const description = photoAlt(listing, current);

  return (
    <div className="mb-4" data-slot="homes-gallery">
      <div className="relative aspect-[16/9] w-full overflow-hidden rounded-site border border-site-border bg-site-bg-subtle">
        <img src={main} alt={altFor(current)} className="h-full w-full object-cover" />
        {listing.aiImages.includes(main) && (
          <span className="absolute end-3 bottom-3 inline-flex items-center gap-1 rounded-site-sm bg-site-media-scrim-strong px-2 py-1 text-xs font-medium text-site-media-ink">
            <Sparkles className="h-3.5 w-3.5" aria-hidden /> {t('generated-by-ai', { defaultValue: 'Generated by AI' })}
          </span>
        )}
      </div>
      {description.kind === 'described' && (
        <p dir="auto" aria-hidden="true" className="t-meta mt-2 break-words" data-slot="homes-photo-caption">
          {description.text}
        </p>
      )}
      {images.length > 1 && (
        <div className="mt-2 flex gap-2 overflow-x-auto">
          {images.map((img, i) => (
            <button
              key={`${i}-${img}`}
              type="button"
              onClick={() => onSelect(i)}
              aria-pressed={i === current}
              className={`relative h-16 w-24 shrink-0 overflow-hidden rounded-site-sm border bg-site-bg-subtle transition-colors duration-(--m1) ${
                i === current ? 'border-site-text' : 'border-site-border hover:border-site-text'
              }`}
            >
              <img src={img} alt={altFor(i)} className="h-full w-full object-cover" />
              {listing.aiImages.includes(img) && (
                <span className="absolute bottom-0.5 right-0.5 grid h-4 w-4 place-items-center rounded-full bg-site-media-scrim-strong text-site-media-ink">
                  <Sparkles className="h-2.5 w-2.5" aria-hidden />
                </span>
              )}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
