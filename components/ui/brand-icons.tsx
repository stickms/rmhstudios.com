/**
 * Brand marks for the OAuth providers on the login page.
 *
 * These used to come from `react-icons/fa`, which cost 85 MB installed to
 * supply exactly three glyphs. Tree-shaking already kept the unused ~50k icons
 * out of the shipped bundle, so the win here is install size and cold CI time
 * rather than runtime bytes — but a three-icon dependency of that weight is not
 * worth carrying.
 *
 * Paths are the Font Awesome 5 brand marks (CC BY 4.0, fontawesome.com/license)
 * on their native 448×512 / 496×512 viewBoxes, unchanged from what `react-icons`
 * rendered — so the glyphs are pixel-identical to what shipped before. The
 * Twitch, GitLab, Steam, X and Reddit marks were added later from
 * `@fortawesome/free-brands-svg-icons` 6.7.2 (same licence; X only exists in 6);
 * Microsoft's four squares are drawn here directly.
 *
 * Each brand's colour lives INSIDE its component rather than in a `className` at
 * the call site. A brand mark is a fixed-palette domain, not themed site UI, so
 * the colour belongs with the mark; this also keeps hex literals out of route
 * code, where the design gate rightly asks about them. GitHub's mark stays on
 * `currentColor` because it is drawn in the surface's ink, exactly as before.
 */

interface BrandIconProps {
  className?: string;
}

