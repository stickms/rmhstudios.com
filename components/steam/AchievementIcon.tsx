/**
 * An achievement's square icon, the way Steam draws one: a flat tile with the
 * icon on it, tinted by tier when unlocked and grey when not. Decorative; the
 * achievement's name is always written beside it.
 */
export function AchievementIcon({
  id,
  tier,
  unlocked,
  size = 64,
  className,
}: {
  id: string;
  tier: AchievementTier;
  unlocked: boolean;
  size?: number;
  className?: string;
}) {
  const Icon =
    ACHIEVEMENT_ICON_COMPONENTS[achievementIconName(id)] ??
    ACHIEVEMENT_ICON_COMPONENTS[DEFAULT_ACHIEVEMENT_ICON];
  return (
    <span
      aria-hidden
      data-tier={tier}
      data-unlocked={unlocked ? 'true' : 'false'}
      className={cn('st-ach-icon', className)}
      style={{ width: size, height: size }}
    >
      <Icon size={Math.round(size * 0.52)} strokeWidth={1.5} />
    </span>
  );
}
