/**
 * Generate `lib/api/route-table.server.ts`: the list of registered API endpoints
 * (third-pass audit AR3).
 *
 * An endpoint registers itself by exporting `route = apiRoute('/api/…', { … })` from a
 * `*.server.ts` module under `lib/` or `features/`. This writes the one module that
 * imports them all, statically, so a registration cannot be dropped at run time by a
 * glob that silently matched nothing. `lib/api/__tests__/route-table.test.ts` fails
 * when the committed table and the tree disagree.
 *
 * Run: `pnpm api:routes` after adding, moving or removing a registered endpoint
 * (`pnpm api:routes:check` only reports).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { API_ROUTE_TABLE, registeredApiRoutes } from '../lib/api/route-sources';

export function renderRouteTable(root: string = process.cwd()): string {
  const routes = registeredApiRoutes(root);
  const seen = new Map<string, string>();
  for (const { file, template } of routes) {
    const other = seen.get(template);
    if (other) throw new Error(`${template} is registered twice: ${other} and ${file}`);
    seen.set(template, file);
  }
  const lines = [
    '/**',
    ' * GENERATED by scripts/gen-api-route-table.ts (`pnpm api:routes`). Do not edit.',
    ' *',
    ' * Every registered API endpoint, sorted by path. `app/routes/api/$.ts` dispatches to',
    ' * these through `lib/api/route-dispatch.server.ts`.',
    ' */',
    "import type { ApiRoute } from '@/lib/api/route.server';",
    ...routes.map(
      ({ file }, i) => `import { route as r${i} } from '@/${file.replace(/\.ts$/, '')}';`,
    ),
    '',
    'export const API_ROUTES: readonly ApiRoute[] = [',
    ...routes.map(({ template }, i) => `  r${i}, // ${template}`),
    '];',
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('gen-api-route-table.ts')) {
  const root = process.cwd();
  const target = join(root, API_ROUTE_TABLE);
  const next = renderRouteTable(root);
  const previous = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (previous === next) {
    process.stdout.write(`${API_ROUTE_TABLE} is up to date.\n`);
  } else if (process.argv.includes('--check')) {
    console.error(`${API_ROUTE_TABLE} is stale. Run \`pnpm api:routes\`.`);
    process.exit(1);
  } else {
    writeFileSync(target, next);
    process.stdout.write(`wrote ${API_ROUTE_TABLE}\n`);
  }
}
