/**
 * Generate `lib/api/route-table.server.ts`: the list of registered API endpoints
 * (third-pass audit AR3).
 *
 * An endpoint registers itself by exporting `route = apiRoute('/api/…', { … })` from a
 * `*.server.ts` module under `lib/` or `features/`. This writes the one module that
 * imports them all, statically, so a registration cannot be dropped at run time by a
 * glob that silently matched nothing. `lib/api/__tests__/route-table.test.ts` fails
 * when the committed table and the tree disagree.
 *
 * Run: `pnpm api:routes` after adding, moving or removing a registered endpoint
 * (`pnpm api:routes:check` only reports).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { API_ROUTE_TABLE, registeredApiRoutes } from '../lib/api/route-sources';

export function renderRouteTable(root: string = process.cwd()): string {
  const routes = registeredApiRoutes(root);
  const seen = new Map<string, string>();
  for (const { file, template } of routes) {
    const other = seen.get(template);
    if (other) throw new Error(`${template} is registered twice: ${other} and ${file}`);
    seen.set(template, file);
  }
  // Every name is derived from the module's own path, never from its position. The table
  // used to number its imports `r0…rN` in sorted order, so inserting one endpoint renumbered
  // every line after it and any two PRs that each added an endpoint conflicted.
  const nameOf = (file: string): string => 'r_' + file.replace(/\.server\.ts$/, '').replace(/[^A-Za-z0-9]+/g, '_');
  const names = new Map<string, string>();
  for (const { file } of routes) {
    const name = nameOf(file);
    const clash = names.get(name);
    if (clash) throw new Error(`${file} and ${clash} would both be named ${name}; rename one`);
    names.set(name, file);
  }

  // One array literal of every route makes tsc build a union of a thousand route types, past
  // its limit (TS2590, "union type that is too complex"). Each bucket is checked against
  // `ApiRoute[]` on its own and the export only spreads them. Buckets are fixed by the first
  // letter of the path segment after /api/ (not by a running count, which shifted every
  // boundary when a route was added), so a route lands in the same bucket for good.
  const bucketOf = (template: string): string => {
    const first = (template.split('/')[2] ?? '').replace(/^\$/, '')[0]?.toLowerCase() ?? '';
    return /[a-z]/.test(first) ? first : '_';
  };
  const buckets = new Map<string, typeof routes>();
  for (const route of routes) {
    const key = bucketOf(route.template);
    buckets.set(key, [...(buckets.get(key) ?? []), route]);
  }
  const keys = [...buckets.keys()].sort();
  const lines = [
    '/**',
    ' * GENERATED by scripts/gen-api-route-table.ts (`pnpm api:routes`). Do not edit.',
    ' *',
    ' * Every registered API endpoint, sorted by path. `app/routes/api/$.ts` dispatches to',
    ' * these through `lib/api/route-dispatch.server.ts`.',
    ' *',
    ' * Each import is named after its module path, and the routes are grouped by the first',
    ' * letter of their path: adding an endpoint changes only its own lines.',
    ' */',
    "import type { ApiRoute } from '@/lib/api/route.server';",
    ...routes.map(({ file }) => `import { route as ${nameOf(file)} } from '@/${file.replace(/\.ts$/, '')}';`),
    '',
    ...keys.flatMap((key) => [
      `const API_ROUTES_${key.toUpperCase()}: readonly ApiRoute[] = [`,
      ...buckets.get(key)!.map(({ file, template }) => `  ${nameOf(file)}, // ${template}`),
      '];',
      '',
    ]),
    'export const API_ROUTES: readonly ApiRoute[] = [',
    ...keys.map((key) => `  ...API_ROUTES_${key.toUpperCase()},`),
    '];',
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('gen-api-route-table.ts')) {
  const root = process.cwd();
  const target = join(root, API_ROUTE_TABLE);
  const next = renderRouteTable(root);
  const previous = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (previous === next) {
    process.stdout.write(`${API_ROUTE_TABLE} is up to date.\n`);
  } else if (process.argv.includes('--check')) {
    console.error(`${API_ROUTE_TABLE} is stale. Run \`pnpm api:routes\`.`);
    process.exit(1);
  } else {
    writeFileSync(target, next);
    process.stdout.write(`wrote ${API_ROUTE_TABLE}\n`);
  }
}
