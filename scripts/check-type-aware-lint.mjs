/* eslint-disable no-console -- CLI script */
// Type-aware lint ratchet (oxlint-tsgolint) over the server tier.
//
//   node scripts/check-type-aware-lint.mjs            fail if any rule's count goes UP
//   node scripts/check-type-aware-lint.mjs --update   rewrite lint-baseline/type-aware.json
//
// no-floating-promises, no-misused-promises and await-thenable need the whole TypeScript program, so they run
// over `server/**` and every `*.server.ts` (tests excluded) with .oxlintrc.typeaware.json. That is about 2300 files,
// 50 s and 7 GB: the whole repo peaks above 11.5 GB, which neither CI nor a laptop can hold beside `tsc`. A floating
// promise in the server tier is a dropped error or a race, which is why it is the tier worth the cost.
// Counts per rule may only go down. The goal is an empty baseline, after which the rules move into .oxlintrc.json.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const BASELINE = 'lint-baseline/type-aware.json';
const OXLINT = path.join('node_modules', 'oxlint', 'bin', 'oxlint');

const listed = spawnSync('git', ['ls-files', 'server/**/*.ts', '**/*.server.ts'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const files = listed.stdout.split('\n').filter((f) => f && !/(__tests__|\.test\.)/.test(f));
const t0 = Date.now();
const run = spawnSync(
  process.execPath,
  [OXLINT, '-c', '.oxlintrc.typeaware.json', '--tsconfig', 'tsconfig.site.json', '-f', 'json', ...files],
  {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    // typescript-go respects the Go memory limit; without it the program grows to ~10 GB
    env: { ...process.env, GOMEMLIMIT: process.env.GOMEMLIMIT ?? '5GiB', GOGC: process.env.GOGC ?? '20' },
  },
);
if (run.error || !run.stdout) {
  console.error(`oxlint did not run: ${run.error?.message ?? run.stderr}`);
  process.exit(2);
}
const diagnostics = JSON.parse(run.stdout).diagnostics;
const counts = {};
for (const d of diagnostics) counts[d.code] = (counts[d.code] ?? 0) + 1;
const secs = ((Date.now() - t0) / 1000).toFixed(0);

if (process.argv.includes('--update')) {
  mkdirSync(path.dirname(BASELINE), { recursive: true });
  writeFileSync(BASELINE, JSON.stringify({ note: 'Generated by `pnpm lint:types:update`. Counts may only go down.', files: files.length, counts }, null, 2) + '\n');
  console.log(`type-aware baseline written (${files.length} files, ${secs}s)`, counts);
  process.exit(0);
}

const base = JSON.parse(readFileSync(BASELINE, 'utf8')).counts;
const worse = [];
const better = [];
for (const rule of new Set([...Object.keys(base), ...Object.keys(counts)])) {
  const was = base[rule] ?? 0;
  const now = counts[rule] ?? 0;
  if (now > was) worse.push(`  ${rule}  ${was} -> ${now}`);
  else if (now < was) better.push(`  ${rule}  ${was} -> ${now}`);
}
if (worse.length) {
  console.error(`lint:types FAILED: type-aware findings increased (${secs}s)\n${worse.join('\n')}`);
  console.error('\nRun `node node_modules/oxlint/bin/oxlint -c .oxlintrc.typeaware.json --tsconfig tsconfig.site.json <file>` on what you changed. Do not raise the baseline.');
  process.exit(1);
}
if (better.length) console.log(`lint:types: improved, shrink the baseline with \`pnpm lint:types:update\` and commit it:\n${better.join('\n')}`);
console.log(`lint:types OK (${files.length} files, ${secs}s)`, counts);
